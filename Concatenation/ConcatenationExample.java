package com.Concatenation;

public class ConcatenationExample {

	public static void main(String[] args) {
		
		System.out.println("Core");
		System.out.println("Java");
		System.out.println("Programs");
		System.out.println("Concatenation Class of Java fundamentals");

//            Concatenation
		System.out.println("Core"+",Java"+","+"Programs");
		System.out.println("Gowlikar"+","+"Susheel"+","+"Raj");
		System.out.println("Gowlikar"+", "+"Kavitha");
		
		int a=20;
		int b=40;
		System.out.println(a+b);
		
		String FirstName="Gowlikar";
		String SecondName="SusheelRaj";
		System.out.println(FirstName+SecondName);
		
	}

}
